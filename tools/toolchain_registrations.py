"""Warns about non-dev toolchain registrations for types a module doesn't own.

A module owns the types in its own repo and in repos generated by its module extensions. A non-dev registration for any
other type injects toolchains into the builds of all of the module's dependents.

Expanding registrations requires Bazel and runs the module's extensions and repo rules. The toolchain_registrations
GitHub workflow runs this script for the module versions a PR adds and reports findings as annotations. Findings never
fail the check.
"""

import argparse
import ast
import json
import os
import pathlib
import re
import secrets
import shutil
import subprocess
import sys
import tempfile
import time
import traceback

from typing import NamedTuple

DISCUSSION_URL = "https://github.com/bazelbuild/bazel/discussions/32428"
MODULE_TIMEOUT_SECONDS = 900
SHUTDOWN_TIMEOUT_SECONDS = 60
WILDCARD_SUFFIXES = ("/...", ":all", ":*", ":all-targets")
# GitHub shows at most 10 warning annotations per step.
MAX_ANNOTATIONS = 10
MAX_ERROR_LINES = 5
TRACEBACK_LOCATION_RE = re.compile(r'^\s*File "([^"]+)", line (\d+), column (\d+)')
# Prefixes of lines in Bazel's output that don't continue an error message. Tabs indent source lines in tracebacks.
NON_MESSAGE_PREFIXES = (
    "\t",
    "    currently ",
    "    Fetching ",
    "Analyzing:",
    "Computing main repo mapping:",
    "DEBUG:",
    "Fetching ",
    "INFO:",
    "Loading:",
    "WARNING:",
)


class AnalysisError(Exception):
    """Raised when it can't be determined which toolchain types a registration applies to."""


class Call(NamedTuple):
    """A register_toolchains call that may not be a dev dependency."""

    line: int
    end_line: int
    # The string literal arguments.
    patterns: list
    # Reasons why (parts of) the call can't be analyzed statically.
    problems: list


class CallResult(NamedTuple):
    call: Call
    # Maps each pattern that registers toolchains for types the module doesn't own to these types.
    foreign: dict
    # (subject, message) pairs explaining why (parts of) the call couldn't be analyzed. The subject is a pattern or None.
    problems: list


class ModuleResult(NamedTuple):
    name: str
    version: str
    path: str
    calls: list

    @property
    def has_findings(self):
        return any(call.foreign for call in self.calls)

    @property
    def is_incomplete(self):
        return any(call.problems for call in self.calls)

    @property
    def status(self):
        if not self.calls:
            return "no non-dev registrations"
        statuses = []
        if self.has_findings:
            statuses.append("registers toolchains for types it doesn't own")
        if self.is_incomplete:
            statuses.append("couldn't be fully analyzed")
        return ", ".join(statuses) or "clean"


def find_registration_calls(module_dot_bazel):
    """Returns the register_toolchains calls in a MODULE.bazel file that may not be dev dependencies."""
    calls = []
    for node in ast.walk(ast.parse(module_dot_bazel)):
        if not (isinstance(node, ast.Call) and getattr(node.func, "id", None) == "register_toolchains"):
            continue
        dev_dependency = next((k.value for k in node.keywords if k.arg == "dev_dependency"), ast.Constant(False))
        if isinstance(dev_dependency, ast.Constant) and dev_dependency.value:
            continue
        if not isinstance(dev_dependency, ast.Constant):
            calls.append(Call(node.lineno, node.end_lineno, [], ["dev_dependency isn't a literal"]))
            continue
        patterns = []
        problems = []
        for arg in node.args:
            if isinstance(arg, ast.Constant) and isinstance(arg.value, str):
                patterns.append(arg.value)
            else:
                problems.append(f"{ast.unparse(arg)} isn't a string literal")
        calls.append(Call(node.lineno, node.end_lineno, patterns, problems))
    return sorted(calls)


def canonicalize_pattern(pattern, own_repo, repo_mapping):
    """Rewrites a target pattern from a module's MODULE.bazel to be valid in any repo."""
    if pattern.startswith("@@"):
        return pattern
    if pattern.startswith("//"):
        return f"@@{own_repo}{pattern}"
    apparent_repo, separator, rest = pattern.removeprefix("@").partition("//")
    if not separator or apparent_repo not in repo_mapping:
        raise AnalysisError(f"can't resolve the repo of {pattern} in the module's repo mapping")
    return f"@@{repo_mapping[apparent_repo]}//{rest}"


def owning_module(label):
    """Returns the name of the module that owns the repo of the given canonical label."""
    canonical_repo = label.removeprefix("@@").partition("//")[0]
    # With Bazel 8 and later, canonical repo names are "<module>+", "<module>+<version>" or
    # "<module>+[<version>]+<extension>+<repo>", where <module> defines the extension. This format isn't an API, but
    # module names can't contain "+".
    return canonical_repo.partition("+")[0]


def get_label_attr(rule, name):
    for attr in rule["attribute"]:
        if attr["name"] == name:
            if "stringValue" not in attr:
                raise AnalysisError(f"{rule['name']} doesn't have a constant value for its {name} attribute")
            return attr["stringValue"]
    raise AnalysisError(f"{rule['name']} doesn't have a {name} attribute")


class RegistrationAnalyzer:
    """Determines which toolchain types registrations apply to."""

    def __init__(self, query_rules):
        """Args: query_rules: Function that returns the parsed rules matching a Bazel query expression."""
        self._query_rules = query_rules
        self._rules = {}

    def _rule(self, label):
        if label not in self._rules:
            rules = self._query_rules(f'"{label}"')
            if len(rules) != 1:
                raise AnalysisError(f"{label} isn't a rule target")
            self._rules[label] = rules[0]
        return self._rules[label]

    def _resolve_aliases(self, rule):
        seen = set()
        while rule["ruleClass"] == "alias":
            if rule["name"] in seen:
                raise AnalysisError(f"{rule['name']} is part of an alias cycle")
            seen.add(rule["name"])
            rule = self._rule(get_label_attr(rule, "actual"))
        return rule

    def toolchain_types(self, pattern):
        """Returns the set of canonical toolchain type labels that the given canonical pattern registers toolchains for.

        Like Bazel, only considers aliases if they are named explicitly.
        """
        kinds = "toolchain" if pattern.endswith(WILDCARD_SUFFIXES) else "toolchain|alias"
        types = set()
        for rule in self._query_rules(f'kind("^({kinds}) rule$", "{pattern}")'):
            self._rules[rule["name"]] = rule
            toolchain = self._resolve_aliases(rule)
            types.add(self._resolve_aliases(self._rule(get_label_attr(toolchain, "toolchain_type")))["name"])
        return types


def describe_bazel_error(stderr, returncode, path_prefixes):
    """Returns the lines of Bazel's output that describe why it failed.

    Prefers the root causes of Starlark errors, prefixed with the innermost location outside of Bazel's builtins, over
    Bazel's ERROR lines. Joins messages that span multiple lines, such as those of fail().
    """
    causes = []
    errors = []
    location = None
    # The list whose last message unrecognized lines continue.
    current = None
    for line in stderr.splitlines():
        for prefix in path_prefixes:
            line = line.replace(prefix, "")
        if not line.strip():
            continue
        if match := TRACEBACK_LOCATION_RE.match(line):
            if not match[1].startswith("/virtual_builtins_bzl/"):
                location = f"{match[1]}:{match[2]}:{match[3]}"
            current = None
        elif line.startswith("Error"):
            causes.append(f"{location}: {line.strip()}" if location else line.strip())
            location = None
            current = causes
        elif line.startswith("ERROR: ") and not line.endswith("Traceback (most recent call last):"):
            errors.append(line.removeprefix("ERROR: ").strip())
            current = errors
        elif current is not None and not line.startswith(NON_MESSAGE_PREFIXES):
            current[-1] = f"{current[-1]} {line.strip()}"
        else:
            current = None
    lines = list(dict.fromkeys(causes or errors))
    if not lines:
        lines = [f"exit code {returncode}"] + [line for line in stderr.splitlines() if line.strip()][-MAX_ERROR_LINES:]
    return "\n".join(lines[:MAX_ERROR_LINES])


class Bazel:
    """Runs Bazel in a workspace whose root module depends on the module to be checked."""

    def __init__(self, registry_root, module_name, version, root, timeout_seconds):
        self._output_base = root / "output_base"
        self._workspace = root / "workspace"
        self._workspace.mkdir()
        if (registry_root / ".bazelversion").exists():
            shutil.copy(registry_root / ".bazelversion", self._workspace)
        (self._workspace / "MODULE.bazel").write_text(f"bazel_dep(name = '{module_name}', version = '{version}')\n")
        (self._workspace / ".bazelrc").write_text(
            f"common --registry={registry_root.as_uri()}\ncommon --lockfile_mode=off\n"
        )
        self._timeout_seconds = timeout_seconds
        self._deadline = time.monotonic() + timeout_seconds
        # Make error messages independent of the host by removing the paths to the output base and the registry.
        self._path_prefixes = []
        for path in dict.fromkeys([self._output_base, self._output_base.resolve()]):
            self._path_prefixes.append(f"{path}/external/")
        for path in dict.fromkeys([registry_root, registry_root.resolve()]):
            self._path_prefixes += [f"{path.as_uri()}/", f"{path}/"]

    def _run(self, *args, timeout=None):
        if timeout is None:
            timeout = self._deadline - time.monotonic()
        try:
            if timeout <= 0:
                raise subprocess.TimeoutExpired(args, timeout)
            return subprocess.run(
                ["bazel", "--nosystem_rc", "--nohome_rc", f"--output_base={self._output_base}", *args],
                cwd=self._workspace,
                capture_output=True,
                text=True,
                timeout=timeout,
            )
        except subprocess.TimeoutExpired:
            raise AnalysisError(f"the analysis took longer than {self._timeout_seconds} seconds")
        except OSError as e:
            raise AnalysisError(f"couldn't run Bazel: {e}")

    def _run_checked(self, *args):
        result = self._run(*args)
        if result.returncode != 0:
            raise AnalysisError(describe_bazel_error(result.stderr, result.returncode, self._path_prefixes))
        return result.stdout

    def repo_mapping(self, canonical_repo):
        return json.loads(self._run_checked("mod", "dump_repo_mapping", canonical_repo))

    def query_rules(self, expression):
        output = self._run_checked("query", "--output=streamed_jsonproto", "--consistent_labels", expression)
        targets = (json.loads(line) for line in output.splitlines())
        return [target["rule"] for target in targets if target["type"] == "RULE"]

    def shutdown(self):
        try:
            self._run("shutdown", timeout=SHUTDOWN_TIMEOUT_SECONDS)
        except AnalysisError:
            pass


def _expand_registrations(bazel, module_name, results):
    try:
        own_repo = bazel.repo_mapping("")[module_name]
        repo_mapping = bazel.repo_mapping(own_repo)
    except AnalysisError as e:
        for result in results:
            if result.call.patterns:
                result.problems.append((None, str(e)))
        return
    analyzer = RegistrationAnalyzer(bazel.query_rules)
    for result in results:
        for pattern in result.call.patterns:
            try:
                types = analyzer.toolchain_types(canonicalize_pattern(pattern, own_repo, repo_mapping))
            except AnalysisError as e:
                result.problems.append((pattern, str(e)))
                continue
            foreign = sorted(t for t in types if owning_module(t) != module_name)
            if foreign:
                result.foreign[pattern] = foreign


def analyze_module(registry_root, module_name, version, timeout_seconds=MODULE_TIMEOUT_SECONDS):
    """Finds the module's non-dev registrations for toolchain types it doesn't own.

    Only runs Bazel if the module has non-dev registrations.
    """
    registry_root = pathlib.Path(registry_root).resolve()
    path = pathlib.PurePosixPath("modules", module_name, version, "MODULE.bazel")
    try:
        calls = find_registration_calls((registry_root / path).read_text())
    except SyntaxError as e:
        line = e.lineno or 1
        call = Call(line, line, [], [])
        return ModuleResult(
            module_name, version, str(path), [CallResult(call, {}, [(None, f"can't parse the file: {e.msg}")])]
        )
    results = [CallResult(call, {}, [(None, problem) for problem in call.problems]) for call in calls]
    if any(call.patterns for call in calls):
        with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as root:
            bazel = Bazel(registry_root, module_name, version, pathlib.Path(root), timeout_seconds)
            try:
                _expand_registrations(bazel, module_name, results)
            finally:
                bazel.shutdown()
    return ModuleResult(module_name, version, str(path), results)


def added_module_versions(registry_root, revision):
    """Returns the module versions whose MODULE.bazel was added between the given Git revision and HEAD."""
    output = subprocess.run(
        ["git", "diff", "--name-only", "--diff-filter=A", "-z", revision, "HEAD", "--", "modules/"],
        cwd=registry_root,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    versions = []
    for path in output.split("\0"):
        parts = path.split("/")
        if len(parts) == 4 and parts[3] == "MODULE.bazel":
            versions.append((parts[1], parts[2]))
    return versions


def format_problems(problems):
    """Returns one line per distinct problem, listing the patterns it applies to."""
    subjects_by_message = {}
    for subject, message in problems:
        subjects_by_message.setdefault(message, []).append(subject)
    lines = []
    for message, subjects in subjects_by_message.items():
        subjects = [subject for subject in subjects if subject]
        lines.append(f"{', '.join(subjects)}: {message}" if subjects else message)
    return lines


def foreign_message(module_name, call_result):
    registrations = "\n".join(f"- {pattern}: {', '.join(types)}" for pattern, types in call_result.foreign.items())
    return (
        f"These registrations apply to all dependents of {module_name}, but the module doesn't own their toolchain"
        f" types:\n{registrations}\nAdd `dev_dependency = True` if only the module's own builds need them. Otherwise,"
        f" ask users to register them in their root module. See {DISCUSSION_URL}."
    )


def incomplete_message(call_result, bazel_version):
    problems = "\n".join(f"- {problem}" for problem in format_problems(call_result.problems))
    analyzed_with = f"\nAnalyzed with Bazel {bazel_version}." if call_result.call.patterns and bazel_version else ""
    return f"Couldn't determine which toolchain types this registers:\n{problems}{analyzed_with}"


def lines_of(call):
    return f"{call.line}" if call.line == call.end_line else f"{call.line}-{call.end_line}"


def format_text_report(results, bazel_version):
    lines = []
    for result in results:
        lines.append(f"{result.name}@{result.version}: {result.status}")
        for call_result in result.calls:
            location = f"{result.path}:{lines_of(call_result.call)}"
            if call_result.foreign:
                lines.append(f"  {location}: {foreign_message(result.name, call_result)}".replace("\n", "\n    "))
            if call_result.problems:
                lines.append(f"  {location}: {incomplete_message(call_result, bazel_version)}".replace("\n", "\n    "))
    return "\n".join(lines)


def _escape_data(value):
    return value.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")


def _escape_property(value):
    return _escape_data(value).replace(":", "%3A").replace(",", "%2C")


def github_annotations(results, bazel_version):
    """Returns workflow commands that annotate the registrations, respecting GitHub's limit per step."""
    annotations = []
    for result in results:
        for call_result in result.calls:
            call = call_result.call
            location = f"file={_escape_property(result.path)},line={call.line},endLine={call.end_line}"
            if call_result.foreign:
                title = f"{result.name} registers toolchains for types it doesn't own"
                message = foreign_message(result.name, call_result)
                annotations.append(f"::warning {location},title={_escape_property(title)}::{_escape_data(message)}")
            if call_result.problems:
                title = f"Couldn't analyze toolchain registrations of {result.name}"
                message = incomplete_message(call_result, bazel_version)
                annotations.append(f"::warning {location},title={_escape_property(title)}::{_escape_data(message)}")
    if len(annotations) > MAX_ANNOTATIONS:
        omitted = len(annotations) - MAX_ANNOTATIONS + 1
        annotations = annotations[: MAX_ANNOTATIONS - 1]
        annotations.append(
            f"::warning::{omitted} more toolchain registration warnings are only listed in the job summary."
        )
    return annotations


def _code_block(text):
    return "```\n" + text.replace("```", "'''") + "\n```"


def github_summary(results, bazel_version):
    """Returns a Markdown summary of all results for the GitHub job summary."""
    lines = ["## Toolchain registrations", ""]
    if not results:
        lines.append("This PR doesn't add any module versions.")
        return "\n".join(lines) + "\n"
    analyzed_with = f" Registrations are expanded with Bazel {bazel_version}." if bazel_version else ""
    lines += [
        "A non-dev `register_toolchains` call applies to all dependents of a module. This check warns about calls that"
        f" register toolchains for types the module doesn't own. See {DISCUSSION_URL}.{analyzed_with}",
        "",
        "| Module version | Result |",
        "| --- | --- |",
    ]
    lines += [f"| `{result.name}@{result.version}` | {result.status} |" for result in results]
    for result in results:
        for call_result in result.calls:
            location = f"`{result.path}:{lines_of(call_result.call)}`"
            if call_result.foreign:
                lines += ["", location, _code_block(foreign_message(result.name, call_result))]
            if call_result.problems:
                lines += ["", location, _code_block(incomplete_message(call_result, bazel_version))]
    return "\n".join(lines) + "\n"


def parse_module_version(value):
    name, separator, version = value.partition("@")
    if not separator or not name or not version:
        raise argparse.ArgumentTypeError(f"expected MODULE@VERSION, got {value}")
    return name, version


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--registry",
        default=".",
        help="Specify the root path of the registry (default: the current working directory).",
    )
    parser.add_argument(
        "--check",
        action="append",
        default=[],
        type=parse_module_version,
        metavar="MODULE@VERSION",
        help="Check the given module version. This flag can be repeated.",
    )
    parser.add_argument(
        "--added_since",
        metavar="REVISION",
        help="Check all module versions whose MODULE.bazel was added between the given Git revision and HEAD.",
    )
    parser.add_argument(
        "--github",
        action="store_true",
        help="Report the results as GitHub Actions annotations and a job summary.",
    )
    args = parser.parse_args(argv)

    if os.getenv("BUILD_WORKSPACE_DIRECTORY"):
        os.chdir(os.getenv("BUILD_WORKSPACE_DIRECTORY"))
    registry_root = pathlib.Path(args.registry).resolve()
    bazel_version_file = registry_root / ".bazelversion"
    bazel_version = bazel_version_file.read_text().strip() if bazel_version_file.exists() else None

    module_versions = set(args.check)
    if args.added_since:
        module_versions.update(added_module_versions(registry_root, args.added_since))

    # Module code controls Bazel's error messages, so don't let GitHub interpret them as workflow commands.
    stop_token = secrets.token_hex(16)
    if args.github:
        print(f"::stop-commands::{stop_token}", flush=True)

    results = []
    crashed = False
    for name, version in sorted(module_versions):
        print(f"Checking {name}@{version}...", flush=True)
        try:
            results.append(analyze_module(registry_root, name, version))
        except Exception:
            traceback.print_exc()
            crashed = True
            path = str(pathlib.PurePosixPath("modules", name, version, "MODULE.bazel"))
            call = Call(1, 1, [], [])
            results.append(ModuleResult(name, version, path, [CallResult(call, {}, [(None, "internal error")])]))
    print(format_text_report(results, bazel_version), flush=True)

    if args.github:
        print(f"::{stop_token}::")
        for annotation in github_annotations(results, bazel_version):
            print(annotation)
        summary_path = os.getenv("GITHUB_STEP_SUMMARY")
        if summary_path:
            with open(summary_path, "a") as summary:
                summary.write(github_summary(results, bazel_version))
    # Findings and incomplete results don't fail the check, but crashes do.
    return 1 if crashed else 0


if __name__ == "__main__":
    sys.exit(main())
